def check_winners(scores, student_score):
    """
    Проверяет, вошёл ли Стас в тройку победителей.

    Сортирует список баллов по убыванию, берёт первые три значения
    и проверяет, находится ли среди них балл Стаса.

    Args:
        scores (list): Список баллов всех участников олимпиады.
        student_score (int): Количество баллов, которое получил Стас.

    Returns:
        None: Функция ничего не возвращает, только печатает результат.
    """
    # Сортируем баллы по убыванию
    sorted_scores = sorted(scores, reverse=True)

    # Берём тройку лидеров
    top_three = sorted_scores[:3]

    # Проверяем, входит ли балл Стаса в тройку
    if student_score in top_three:
        print("Вы в тройке победителей!")
    else:
        print("Вы не попали в тройку победителей.")


# Пример использования
scores = [20, 48, 52, 38, 36, 13, 7, 41, 34, 24, 5, 51, 9, 14, 28]
student_score = 48

check_winners(scores, student_score)
